// English and Vietnamese (CLIENT.md, "Languages").
//
// The English text is the key: in app.js a sentence is written as a tagged
// template, T`${who} breaks`, whose key is "{0} breaks"; in Vietnamese VI
// maps it to "{0} phá bi" (the placeholders may move). English shows the
// sentence as written, so the English page is the code's own words. A plain
// string kept in a table is marked N('...') where it is defined and
// translated with tr() where it is shown. The static page (index.html) is
// walked once at start: its text and its aria-label, title, placeholder and
// aria-valuetext are remembered in English and set in the language chosen,
// again whenever it changes. An element marked translate="no" (the
// wordmark) is left alone.
//
// A sentence missing from VI shows in English and is listed in
// window.__i18nMissing (e2e/i18n.js fails on any).

let LANG = 'en';

// detectLang: the language picked before (pool:lang), else the browser's.
function detectLang() {
  let saved = null;
  try { saved = localStorage.getItem('pool:lang'); } catch { /* unavailable */ }
  if (saved === 'en' || saved === 'vi') return saved;
  const langs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'en'];
  return langs.some((l) => /^vi\b/i.test(l)) ? 'vi' : 'en';
}

window.__i18nMissing = new Set();

// tr translates one English string (a key). A key may end in |context
// where one English word means two things ("Game|match"); English drops it.
function tr(key) {
  if (!key) return key;
  if (LANG === 'en') return key.replace(/\|[a-z]+$/, '');
  const v = VI[key];
  if (v === undefined) { window.__i18nMissing.add(key); return key.replace(/\|[a-z]+$/, ''); }
  return v;
}

// T is the tag for sentences with values: T`${a} wins ${b}–${c}`.
function T(strings, ...vals) {
  let key = strings[0];
  for (let i = 1; i < strings.length; i++) key += `{${i - 1}}` + strings[i];
  const tpl = tr(key);
  return vals.length ? tpl.replace(/\{(\d+)\}/g, (_, i) => String(vals[i])) : tpl;
}

// N marks a string kept in a table as one to translate (with tr) where it
// is shown; it returns it unchanged.
const N = (s) => s;

// --- the static page ---------------------------------------------------------

const I18N_ATTRS = ['aria-label', 'title', 'placeholder', 'aria-valuetext'];
let i18nTexts = null; // [{node, en, shown}]
let i18nAttrs = null; // [{el, attr, en, shown}]

function collectStatic() {
  i18nTexts = [];
  i18nAttrs = [];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode(n) {
      if (!/[A-Za-z]/.test(n.nodeValue)) return NodeFilter.FILTER_REJECT;
      if (n.parentElement.closest('[translate="no"], script, style, svg')) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });
  for (let n = walker.nextNode(); n; n = walker.nextNode()) i18nTexts.push({ node: n, en: n.nodeValue, shown: n.nodeValue });
  for (const el of document.body.querySelectorAll(I18N_ATTRS.map((a) => `[${a}]`).join(','))) {
    if (el.closest('[translate="no"]')) continue;
    for (const attr of I18N_ATTRS) {
      const v = el.getAttribute(attr);
      if (v && /[A-Za-z]/.test(v)) i18nAttrs.push({ el, attr, en: v, shown: v });
    }
  }
}

// applyStatic sets the page's own words in LANG. A node or attribute the
// code has rewritten since is the code's to translate and is dropped.
function applyStatic() {
  if (!i18nTexts) collectStatic();
  i18nTexts = i18nTexts.filter((r) => r.node.isConnected && r.node.nodeValue === r.shown);
  for (const r of i18nTexts) {
    const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(r.en);
    r.shown = m[1] + tr(m[2]) + m[3];
    if (r.node.nodeValue !== r.shown) r.node.nodeValue = r.shown;
  }
  i18nAttrs = i18nAttrs.filter((r) => r.el.getAttribute(r.attr) === r.shown);
  for (const r of i18nAttrs) {
    r.shown = tr(r.en);
    r.el.setAttribute(r.attr, r.shown);
  }
}

